"""Generate the synthetic sample dataset in data/sample/.

The repository ships NO real marketplace data and never downloads any.  This script
fabricates a realistic-looking portfolio so the model runs out of the box:

* weekly history (52 weeks): market price, units sold, transactions, low/high sale
* a snapshot of the ask ladder (every listing: price, shipping, quantity)

Each item has its own liquidity profile (sales rate, clumpiness, queue depth, volatility),
chosen to cover the cases the model cares about: slow expensive singles, fast cheap ones,
deep sealed-product queues, and reprint-exposed items.  All numbers are made up.

Run: python scripts/make_sample_data.py   (deterministic: fixed seed)
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "sample"
SEED = 7
WEEKS = 52

# id, name, qty, reprint, start price, sold/day, dispersion φ, weekly vol, weekly drift,
# listings in queue, share of listings priced below market, weekly sale-range width
ITEMS = [
    ("card_a", "Card A · chase single",        1, False, 2100, 0.25, 2.5, 0.05,  0.002,  30, 0.12, 0.10),
    ("card_b", "Card B · alt-art single",      1, False, 1300, 0.18, 1.5, 0.04, -0.001,  25, 0.20, 0.12),
    ("card_c", "Card C · new-set chase card",  2, True,  1500, 0.50, 1.8, 0.08, -0.004,  50, 0.10, 0.14),
    ("card_d", "Card D · mid-value single",    3, True,   500, 0.65, 3.5, 0.06,  0.000,  55, 0.08, 0.10),
    ("box_e",  "Box E · sealed booster box",   1, False, 2200, 0.65, 9.0, 0.03,  0.003, 135, 0.02, 0.06),
    ("box_f",  "Box F · premium collection",   2, False,  850, 1.10, 10.0, 0.04, 0.001, 150, 0.03, 0.08),
    ("box_g",  "Box G · exclusive box",        4, False, 1200, 0.22, 1.8, 0.05,  0.000,  70, 0.10, 0.09),
]


def negbin(rng, mean: float, phi: float) -> int:
    """Draw from NegBin with the given mean and variance φ·mean (Poisson if φ ≈ 1)."""
    if mean <= 0:
        return 0
    if phi <= 1.0001:
        return int(rng.poisson(mean))
    n = mean / (phi - 1.0)
    return int(rng.negative_binomial(n, 1.0 / phi))


def weekly(rng, p0, lam, phi, vol, drift):
    dates = np.datetime64("2025-10-06") + np.arange(WEEKS) * np.timedelta64(7, "D")
    logp = np.log(p0) + np.cumsum(rng.normal(drift, vol, WEEKS))
    # a couple of jumps so the tails are not Gaussian
    for k in rng.choice(WEEKS, size=2, replace=False):
        logp[k:] += rng.normal(0, 2.5 * vol)
    logp += np.log(p0) - logp[-1]        # anchor today's price at p0 so the profiles stay comparable
    rows = []
    for d, lp in zip(dates, logp):
        qty = negbin(rng, 7 * lam, phi)
        txn = int(min(qty, max(0, round(qty * rng.uniform(0.7, 1.0)))))
        mkt = float(np.exp(lp))
        if txn >= 2:
            w = abs(rng.normal(0, 1)) + 0.3
            low, high = mkt * (1 - w * 0.5 * vol * 2), mkt * (1 + w * 0.5 * vol * 2)
        elif txn == 1:
            low = high = mkt * (1 + rng.normal(0, vol / 2))
        else:
            low = high = float("nan")
        rows.append({"date": str(d), "market": round(mkt, 2), "qty": qty, "txn": txn,
                     "low": "" if np.isnan(low) else round(low, 2),
                     "high": "" if np.isnan(high) else round(high, 2)})
    return rows


def ladder(rng, market, n, below, width):
    rows = []
    for _ in range(n):
        if rng.random() < below:          # a few sellers already undercutting the market
            price = market * rng.uniform(0.82, 0.99)
        else:                             # most sit at or above market, a long right tail
            price = market * (1 + rng.exponential(width * 1.5))
        ship = float(rng.choice([0.0, 0.0, 1.31, 4.99]))
        qty = int(rng.choice([1, 1, 1, 1, 2, 3]))
        rows.append({"price": round(price, 2), "shipping": ship, "qty": qty})
    return sorted(rows, key=lambda r: r["price"] + r["shipping"])


def main():
    rng = np.random.default_rng(SEED)
    (OUT / "weekly").mkdir(parents=True, exist_ok=True)
    (OUT / "listings").mkdir(parents=True, exist_ok=True)
    positions = []
    for (iid, name, qty, reprint, p0, lam, phi, vol, drift, depth, below, width) in ITEMS:
        wk = weekly(rng, p0, lam, phi, vol, drift)
        lad = ladder(rng, wk[-1]["market"], depth, below, width)
        for sub, rows in (("weekly", wk), ("listings", lad)):
            with open(OUT / sub / f"{iid}.csv", "w", newline="", encoding="utf-8") as f:
                w = csv.DictWriter(f, fieldnames=list(rows[0]))
                w.writeheader()
                w.writerows(rows)
        positions.append({"id": iid, "name": name, "qty": qty, "reprint_risk": reprint})
    (OUT / "portfolio.json").write_text(json.dumps({
        "_note": "SYNTHETIC sample portfolio generated by scripts/make_sample_data.py. Not real market data.",
        "positions": positions}, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"wrote {len(positions)} items to {OUT}")


if __name__ == "__main__":
    main()
